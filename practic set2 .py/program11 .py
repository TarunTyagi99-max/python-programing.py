#Input a number. Display: Result after left shifting by 2 bits (<< 2) and Result after right shifting by 2 bits (>> 2)

num = int(input("Enter a number: "))
left_shift = num << 2
right_shift = num >> 2
print(f"Result after left shifting by 2 bits (<< 2): {left_shift}")
print(f"Result after right shifting by 2 bits (>> 2): {right_shift}")



