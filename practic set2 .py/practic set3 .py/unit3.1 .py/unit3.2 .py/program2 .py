#Count occurrence of a specific value. Also, find the index of a given element.
tuple = (10,20,30,40,50,10,20,30,40)
print("count of 10 in tuple:", tuple.count(10))
print("index of 30 in tuple:", tuple.index(30))
print("count of 20 in tuple:", tuple.count(20))
print("index of 40 in tuple:", tuple.index(40))
print("count of 50 in tuple:", tuple.count(50))
print("index of 50 in tuple:", tuple.index(50))