# Write a program to input two integers and display: Addition, Subtraction, Multiplication, Division, Floor Division, Modulus and Exponentiation
num1 = int(input("enter first number:"))
num2 = int(input("enter second number: "))
add = num1 + num2
sub = num1 - num2
mul = num1 * num2
div = num1 / num2
floor_div = num1 // num2
mod = num1 % num2
exp = num1 ** num2
print("add", add)
print("sub", sub)
print("mul", mul)
print("div", div)
print("floor_div", floor_div)
print("mod", mod)
print("exp", exp)
